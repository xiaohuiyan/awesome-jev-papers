"""Render the bilingual catalogue and BibTeX from the reviewed JSON dataset."""
from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "papers.json"


def load():
    return json.loads(DATA.read_text(encoding="utf-8"))


def ordered(papers):
    return sorted(papers, key=lambda p: (p["first_submitted"], p["arxiv_id"]), reverse=True)


def authors(p):
    names = p["authors"]
    return ", ".join(names[:3]) + (", et al." if len(names) > 3 else "")


def readme(data, lang):
    zh = lang == "zh"
    papers = data["papers"]
    counts = Counter(p["relation_level"] for p in papers)
    links = sum(bool(p["code"]) for p in papers)
    lines = ["<!-- Generated by scripts/render.py; edit data/papers.json instead. -->",
             "# Awesome Jev Papers", "",
             "[English](README.md) · [简体中文](README.zh-CN.md)", ""]
    if zh:
        lines += ["围绕 **Jev、System One 和结构化决策模型**整理的 arXiv 论文目录。重点关注直接返回候选概率的模型，以及它们在智能体中的方法、评测和应用。", "",
                  f"**更新：{data['updated_on']}** · **{len(papers)} 篇** · Jev 直接相关 **{counts['direct']}** · 同类模型与方法 **{counts['related']}** · 基础背景 **{counts['background']}** · 已核实作者代码链接 **{links} 篇**", "",
                  "主要时间范围：**2025-10-16 至 2026-10-16**，按首次提交日期筛选；每篇标明本次核实的版本。较早的基础工作单列。", "",
                  "Jev 指 TypeSafe 的托管模型。同类模型采用相近接口，不代表复制了 Jev 的专有架构或训练方法。简介描述论文研究内容；预印本结论不等于独立复现结果，跨论文指标不可直接组成排行榜。", "",
                  "**数据与维护：** [结构化数据](data/papers.json) · [BibTeX](references.bib) · [收录规则](docs/METHODOLOGY.md) · [检索记录](docs/SEARCH_LOG.md) · [筛选台账](data/screening.json) · [待核实](docs/PENDING.md) · [贡献指南](CONTRIBUTING.md)", ""]
    else:
        lines += ["A curated arXiv reading list on **Jev, System One, and typed decision models**: models that return probabilities over supplied options, and the methods, evaluations, and agent applications built around them.", "",
                  f"**Updated: {data['updated_on']}** · **{len(papers)} papers** · **{counts['direct']}** directly related to Jev · **{counts['related']}** related models and methods · **{counts['background']}** foundations · **{links}** papers with verified author-linked code", "",
                  "Main window: **2025-10-16 through 2026-10-16**, by first submission. Each entry pins the version reviewed for this snapshot. Earlier foundations are listed separately.", "",
                  "Jev means TypeSafe's hosted model. Similar interfaces do not establish reproduction of its proprietary architecture or training. Notes describe the research, not independently reproduced results. Preprints and results from different experimental setups should not be read as a shared performance leaderboard.", "",
                  "**Data and maintenance:** [JSON](data/papers.json) · [BibTeX](references.bib) · [Selection rules](docs/METHODOLOGY.md) · [Search log](docs/SEARCH_LOG.md) · [Screening ledger](data/screening.json) · [Pending](docs/PENDING.md) · [Contributing](CONTRIBUTING.md)", ""]
    lines += ["## " + ("目录" if zh else "Contents"), "",
              "- [" + ("推荐阅读" if zh else "Recommended reading") + "](#recommended-reading)",
              "- [" + ("分类统计" if zh else "Category index") + "](#category-index)"]
    for key, cat in data["categories"].items():
        lines.append(f"- [{cat[lang]}](#{key})")
    lines += ["- [" + ("基础背景" if zh else "Foundations") + "](#foundations)",
              "- [" + ("复用与更新" if zh else "Reuse and updates") + "](#reuse-and-updates)", "",
              '<a id="recommended-reading"></a>', "## " + ("推荐阅读" if zh else "Recommended reading"), "",
              ("以下 10 篇按阅读路径排列，覆盖综述、基准、模型、校准、安全和应用；不是性能排名。完整分类目录收录其余合格论文。" if zh else
               "Ten starting points arranged as a reading path across evidence reviews, benchmarks, models, calibration, security, and applications. This is not a performance ranking; all other included papers remain in the catalogue."), ""]
    by_id = {p["arxiv_id"]: p for p in papers}
    for pid in data["recommended"]:
        p = by_id[pid]
        lines.append(f"- [{p['title']}](#paper-{pid.replace('.', '-')}) — {p['summary'][lang]}")
    lines += ["", '<a id="category-index"></a>', "## " + ("分类统计" if zh else "Category index"), "",
              ("| 主题 | Jev 直接相关 | 同类模型与方法 | 合计 |" if zh else "| Topic | Direct Jev | Related methods | Total |"),
              "| --- | ---: | ---: | ---: |"]
    for key, cat in data["categories"].items():
        sub = [p for p in papers if p["primary_category"] == key and p["relation_level"] != "background"]
        n = Counter(p["relation_level"] for p in sub)
        lines.append(f"| [{cat[lang]}](#{key}) | {n['direct']} | {n['related']} | {len(sub)} |")
    lines += ["", ("每篇只计入一个主分类，交叉主题通过标签表示；另有 4 篇基础背景。分类内按首次提交日期倒序排列。" if zh else
                   "Each paper has one primary category and cross-topic tags. Four foundations are counted separately. Within each section, entries are ordered by first submission, newest first."), ""]
    labels = {"direct": "Jev 直接相关" if zh else "Direct Jev",
              "related": "同类模型与方法" if zh else "Related model / method",
              "background": "基础背景" if zh else "Foundation"}

    def entry(p):
        pid = p["arxiv_id"]
        result = [f'<a id="paper-{pid.replace(".", "-")}"></a>',
                  f"### [{p['title']}]({p['reviewed_url']})", "",
                  f"{authors(p)} · {p['first_submitted']} · **v{p['version']}** · **{labels[p['relation_level']]}**", "",
                  p["summary"][lang], ""]
        resources = [f"[arXiv]({p['arxiv_url']})", f"[PDF]({p['pdf_url']})"]
        if p["code"]:
            for i, c in enumerate(p["code"]):
                label = ("作者代码" if zh else "Author code") + (f" {i + 1}" if len(p["code"]) > 1 else "")
                resources.append(f"[{label}]({c['url']})")
        else:
            resources.append("作者代码未核实" if zh else "Author code not verified")
        resources.append(f"[{'证据' if zh else 'Evidence'}](docs/EVIDENCE.md#evidence-{pid.replace('.', '-')})")
        result += [" · ".join(resources) + "<br>",
                   ("标签：" if zh else "Tags: ") + " · ".join(f"`{t}`" for t in p["tags"]), ""]
        return result

    for key, cat in data["categories"].items():
        lines += [f'<a id="{key}"></a>', f"## {cat[lang]}", ""]
        for tier in ("direct", "related"):
            sub = ordered([p for p in papers if p["primary_category"] == key and p["relation_level"] == tier])
            if not sub:
                continue
            lines += [f"**{labels[tier]} ({len(sub)})**", ""]
            for p in sub:
                lines += entry(p)
    lines += ['<a id="foundations"></a>', "## " + ("基础背景" if zh else "Foundations"), "",
              ("以下工作早于主要时间窗口，用于理解校准、拒答、级联和动态标签分类；不计入 Jev 直接评测。" if zh else
               "Earlier work on calibration, rejection, cascades, and generalist classification. These papers provide context and are not Jev evaluations."), ""]
    for p in ordered([p for p in papers if p["relation_level"] == "background"]):
        lines += entry(p)
    lines += ['<a id="reuse-and-updates"></a>', "## " + ("复用与更新" if zh else "Reuse and updates"), ""]
    if zh:
        lines += ["完整作者、首次提交与修订日期、版本、关联说明和短证据引文保存在 [JSON](data/papers.json) 与 [证据台账](docs/EVIDENCE.md)。代码链接仅表示作者指向的公开仓库可访问，不代表代码已经复现。", "",
                  "更新时编辑数据，再运行下列命令。GitHub Actions 检查数据与文档一致性，不自动添加论文。", ""]
    else:
        lines += ["Full author lists, submission and revision dates, versions, relation notes, and short evidence excerpts are available in [JSON](data/papers.json) and the [evidence ledger](docs/EVIDENCE.md). A code link means an author-linked public repository was reachable, not that its experiments were reproduced.", "",
                  "Edit the data, then run the commands below. GitHub Actions checks catalogue consistency; it does not automatically add papers.", ""]
    lines += ["```sh", "python scripts/render.py", "python scripts/validate.py", "```", "",
              "[Changelog](CHANGELOG.md) · [Contributing](CONTRIBUTING.md) · [CC BY 4.0](LICENSE)", "",
              ("原创整理内容使用 CC BY 4.0；脚本使用 MIT。论文、数据集和第三方代码保留其各自许可。本仓库不托管论文全文，也不代表 TypeSafe 或任何模型作者。" if zh else
               "Original curation is CC BY 4.0; scripts are MIT. Papers, datasets, and third-party code retain their own licenses. This repository does not host paper full texts and is not affiliated with TypeSafe or the model authors."), ""]
    return "\n".join(lines)


def evidence(data):
    lines = ["<!-- Generated by scripts/render.py. -->", "# Evidence ledger / 收录证据", "",
             "Short excerpts support relevance decisions, not paper quality or reproducibility. Scores measure topic fit and substantive contribution only. Abstract-level review is the default; targeted full-text checks are marked. 引文用于核实相关性，不是论文质量或模型性能评分。", ""]
    for p in ordered(data["papers"]):
        pid = p["arxiv_id"]
        lines += [f'<a id="evidence-{pid.replace(".", "-")}"></a>',
                  f"## {pid} — {p['title']}", "",
                  f"**{p['relation_level']}** · Relevance {p['relevance']['weighted_total']:.2f} · {p['review_level']} · Verified {p['verified_on']}", "",
                  p["relation"]["en"], "", p["relation"]["zh"], ""]
        for e in p["evidence"]:
            lines.append(f"- **{e['criterion']}**: “{e['quote']}” — [{e['location']}]({e['source_url']})")
        lines += ["", f"Metadata: [reviewed v{p['version']}]({p['reviewed_url']}); first submitted {p['first_submitted']}; updated {p['updated']}. Full authors: " + "; ".join(p["authors"]) + ".", ""]
    return "\n".join(lines)


def bib_escape(s):
    return s.replace("\\", r"\textbackslash{}").replace("{", r"\{").replace("}", r"\}").replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#").replace("$", r"\$")


def bibtex(data):
    lines = ["% Generated from data/papers.json. Versions pin the reviewed snapshot.", ""]
    for p in ordered(data["papers"]):
        lines += ["@misc{arxiv" + p["arxiv_id"].replace(".", "") + ",",
                  "  title = {{" + bib_escape(p["title"]) + "}},",
                  "  author = {" + " and ".join(bib_escape(n) for n in p["authors"]) + "},",
                  "  year = {" + p["first_submitted"][:4] + "},",
                  "  eprint = {" + p["arxiv_id"] + "},",
                  "  archivePrefix = {arXiv},",
                  "  primaryClass = {" + p["arxiv_categories"][0] + "},",
                  "  url = {" + p["reviewed_url"] + "},",
                  "  note = {Version " + str(p["version"]) + "; reviewed " + data["updated_on"] + "}", "}", ""]
    return "\n".join(lines)


def outputs(data):
    return {"README.md": readme(data, "en"), "README.zh-CN.md": readme(data, "zh"),
            "docs/EVIDENCE.md": evidence(data), "references.bib": bibtex(data)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed generated files are stale")
    args = parser.parse_args()
    stale = []
    for name, content in outputs(load()).items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Stale generated files: " + ", ".join(stale))
    print("Generated files are current." if args.check else "Rendered bilingual catalogue, evidence and BibTeX.")


if __name__ == "__main__":
    main()
