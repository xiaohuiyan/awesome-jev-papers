"""Render the bilingual catalogue and BibTeX from the reviewed JSON dataset."""
from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "papers.json"

CATEGORY_QUESTIONS = {
    "architecture": {"zh": "怎样训练一个专门做选择的模型？", "en": "How do we train a model specifically to choose?"},
    "evaluation": {"zh": "快决策在哪些任务上够用？", "en": "When are fast decisions good enough?"},
    "calibration": {"zh": "模型说有把握，真的可靠吗？", "en": "Can we trust the model's confidence?"},
    "agents": {"zh": "何时搜索、调用工具或交给更强的模型？", "en": "When should an agent search, use a tool, or delegate?"},
    "security": {"zh": "换个问法或选项顺序，会不会改变判断？", "en": "Can phrasing, option order, or attacks change the decision?"},
    "applications": {"zh": "放进真实工作流，质量与速度如何取舍？", "en": "How do quality and speed trade off in real workflows?"},
}


def load():
    return json.loads(DATA.read_text(encoding="utf-8"))


def ordered(papers):
    return sorted(papers, key=lambda p: (p["first_submitted"], p["arxiv_id"]), reverse=True)


def readme(data, lang):
    zh = lang == "zh"
    papers = data["papers"]
    counts = Counter(p["relation_level"] for p in papers)
    links = sum(bool(p["code"]) for p in papers)
    lines = ["<!-- Generated by scripts/render.py; edit data/papers.json and scripts/render.py instead. -->",
             '<a id="top"></a>', "# Awesome Jev Papers", "",
             "[English](README.md) · [简体中文](README.zh-CN.md)", ""]
    if zh:
        lines += ["> **让模型做选择，让程序执行。** 从 Jev 出发，理解 System One 与类型化决策模型（TDM）的能力、边界和应用。", "",
                  "这份论文库关注一个具体问题：给定上下文和候选项，模型能否快速给出可信的选择概率？例如，智能体读完检索结果后，可以先判断“证据够了”还是“继续搜索”，再由程序执行对应操作。", "",
                  "**典型用法：** 上下文 + 候选项 → 模型给出概率 → 应用策略选择执行、拒答或转交。", ""]
    else:
        lines += ["> **Models choose. Programs act.** Explore the capabilities, limits, and applications of Jev, System One, and typed decision models (TDMs).", "",
                  "This reading list asks a concrete question: given context and a set of options, can a model quickly assign trustworthy choice probabilities? For example, after reading search results, an agent can decide whether it has enough evidence or needs another search, then let code carry out the selected action.", "",
                  "**Typical workflow:** Context + options → model probabilities → application policy executes, abstains, or delegates.", ""]
    lines += [("| 收录论文 | Jev 直接相关 | 同类模型与方法 | 基础背景 | 含已核实代码 |" if zh else
               "| Papers | Direct Jev | Related methods | Foundations | With verified code |"),
              "| ---: | ---: | ---: | ---: | ---: |",
              f"| **{len(papers)}** | {counts['direct']} | {counts['related']} | {counts['background']} | {links} |", "",
              (f"更新于 **{data['updated_on']}** · 主要收录窗口 **{data['window']['start']}—{data['window']['end']}**（首次提交日期）" if zh else
               f"Updated **{data['updated_on']}** · Main window **{data['window']['start']}–{data['window']['end']}** (first submission)"), "",
              ("[十篇入门](#recommended-reading) · [按问题选文](#category-index) · [基础背景](#foundations) · [数据与维护](#reuse-and-updates)" if zh else
               "[Start with ten papers](#recommended-reading) · [Browse by question](#category-index) · [Foundations](#foundations) · [Data and maintenance](#reuse-and-updates)"), "",
              "<details>", "<summary>" + ("阅读前：范围、证据与结论边界" if zh else "Before reading: scope, evidence, and limitations") + "</summary>", "",
              ("Jev 指 TypeSafe 的托管模型。同类模型采用相近接口，不代表复制了 Jev 的专有架构或训练方法。每篇保留英文原标题及已核实版本，较早的基础工作单列。" if zh else
               "Jev means TypeSafe's hosted model. Similar interfaces do not establish reproduction of its proprietary architecture or training. Entries retain original English titles and pin reviewed versions; earlier foundations are listed separately."), "",
              ("简介描述论文报告的研究，并非独立复现结果。预印本结论需要结合任务、数据和实验设置理解；跨论文指标不能直接组成排行榜。代码链接只表示已核实作者指向的公开仓库，不表示已复现代码。" if zh else
               "Notes summarize reported research, not independent replications. Interpret preprint findings in the context of their tasks, data, and experimental setups; cross-paper metrics are not a shared leaderboard. Code links identify verified author-linked public repositories, not reproduced experiments."), "",
              "</details>", "",
              '<a id="recommended-reading"></a>', "## " + ("推荐阅读" if zh else "Recommended reading"), "",
              ("建议路径：**看清证据 → 比较能力 → 理解模型 → 管理风险 → 接入应用**。以下十篇是阅读入口，不是性能排名；点击短标题查看完整条目。" if zh else
               "Suggested path: **assess the evidence → compare capabilities → understand models → manage risk → build applications**. These ten papers are starting points, not a ranking. Follow a short title to its full entry."), "",
              ("| 顺序 | 论文入口 | 带着这个问题读 |" if zh else "| Step | Paper | Read to answer |"),
              "| ---: | --- | --- |"]
    by_id = {p["arxiv_id"]: p for p in papers}
    for i, pid in enumerate(data["recommended"], 1):
        p = by_id[pid]
        guide = p["reading_guide"]
        lines.append(f"| {i} | [{guide['label'][lang]}](#paper-{pid.replace('.', '-')}) | {guide['question'][lang]} |")
    lines += ["", '<a id="category-index"></a>', "## " + ("按问题选文" if zh else "Browse by question"), "",
              ("| 你想了解什么？ | 主题 | 直接 / 相关 | 合计 |" if zh else "| Your question | Topic | Direct / related | Total |"),
              "| --- | --- | ---: | ---: |"]
    for key, cat in data["categories"].items():
        sub = [p for p in papers if p["primary_category"] == key and p["relation_level"] != "background"]
        n = Counter(p["relation_level"] for p in sub)
        lines.append(f"| {CATEGORY_QUESTIONS[key][lang]} | [{cat[lang]}](#{key}) | {n['direct']} / {n['related']} | {len(sub)} |")
    lines += ["", (f"每篇只计入一个主分类；另有 {counts['background']} 篇基础背景。每类先列 Jev 直接相关，再列同类方法；组内按首次提交日期倒序排列。条目保留发表时间、作者、解决问题与核心贡献四项；完整作者名单、标签与核实记录见[证据台账](docs/EVIDENCE.md)与 [BibTeX](references.bib)。" if zh else
                   f"Each paper has one primary category; {counts['background']} foundations are listed separately. Categories group direct Jev work before related methods, with newest first submissions first within each group. Entries keep four fields: published date, authors, problem, and contribution. Full author lists, tags, and verification records live in the [evidence ledger](docs/EVIDENCE.md) and [BibTeX](references.bib)."), ""]
    labels = {"direct": "Jev 直接相关" if zh else "Direct Jev",
              "related": "同类模型与方法" if zh else "Related model / method",
              "background": "基础背景" if zh else "Foundation"}

    def entry(p, heading="####"):
        pid = p["arxiv_id"]
        names = [n.strip() for n in p["authors"]]  # arXiv metadata can carry stray padding
        if len(names) > 4:
            shown = "；".join(names[:3]) + f" 等（共 {len(names)} 位）" if zh else "; ".join(names[:3]) + f" et al. ({len(names)} authors)"
        else:
            shown = "；".join(names) if zh else "; ".join(names)
        fields = [("📅 " + ("发表时间" if zh else "Published"), f"{p['first_submitted']}（v{p['version']}）" if zh else f"{p['first_submitted']} (v{p['version']})"),
                  ("👥 " + ("作者" if zh else "Authors"), shown),
                  ("🎯 " + ("解决问题" if zh else "Problem"), p["problem"][lang]),
                  ("💡 " + ("核心贡献" if zh else "Contribution"), p["summary"][lang])]
        resources = [f"[PDF]({p['pdf_url']})"]
        for i, c in enumerate(p["code"]):
            label = ("作者代码" if zh else "Author code") + (f" {i + 1}" if len(p["code"]) > 1 else "")
            resources.append(f"[{label}]({c['url']})")
        return [f'<a id="paper-{pid.replace(".", "-")}"></a>',
                f"{heading} [{p['title']}]({p['reviewed_url']})",
                " · ".join(resources),
                *[f"- **{name}**：{value}" if zh else f"- **{name}**: {value}" for name, value in fields],
                "---"]

    for key, cat in data["categories"].items():
        lines += [f'<a id="{key}"></a>', f"## {cat[lang]}", "",
                  f"> {CATEGORY_QUESTIONS[key][lang]}", "",
                  ("[返回分类导航](#category-index)" if zh else "[Back to category index](#category-index)"), ""]
        for tier in ("direct", "related"):
            sub = ordered([p for p in papers if p["primary_category"] == key and p["relation_level"] == tier])
            if not sub:
                continue
            lines += [f"### {labels[tier]} · {len(sub)}", ""]
            for p in sub:
                lines += entry(p)
    lines += ['<a id="foundations"></a>', "## " + ("基础背景" if zh else "Foundations"), "",
              ("以下工作早于主要时间窗口，用于理解校准、拒答、级联和动态标签分类；不计入 Jev 直接评测。" if zh else
               "Earlier work on calibration, rejection, cascades, and generalist classification. These papers provide context and are not Jev evaluations."), ""]
    for p in ordered([p for p in papers if p["relation_level"] == "background"]):
        lines += entry(p, "###")
    lines += ['<a id="reuse-and-updates"></a>', "## " + ("复用与更新" if zh else "Reuse and updates"), ""]
    if zh:
        lines += ["| 用途 | 入口 |", "| --- | --- |",
                  "| 下载与引用 | [结构化 JSON](data/papers.json) · [BibTeX](references.bib) |",
                  "| 核实收录依据 | [证据台账](docs/EVIDENCE.md) · [收录规则](docs/METHODOLOGY.md) |",
                  "| 了解检索覆盖 | [检索记录](docs/SEARCH_LOG.md) · [社交平台检索](docs/SOCIAL_SEARCH_2026-10-17.md) |",
                  "| 查看筛选过程 | [筛选台账](data/screening.json) · [待核实](docs/PENDING.md) |",
                  "| 参与维护 | [贡献指南](CONTRIBUTING.md) · [更新记录](CHANGELOG.md) |", "",
                  "更新时编辑数据，再运行下列命令。GitHub Actions 检查数据与文档一致性，不自动添加论文。", ""]
    else:
        lines += ["| Purpose | Resources |", "| --- | --- |",
                  "| Download and cite | [JSON](data/papers.json) · [BibTeX](references.bib) |",
                  "| Check inclusion evidence | [Evidence ledger](docs/EVIDENCE.md) · [Selection rules](docs/METHODOLOGY.md) |",
                  "| Understand search coverage | [Search log](docs/SEARCH_LOG.md) · [Social-platform search](docs/SOCIAL_SEARCH_2026-10-17.md) |",
                  "| Inspect screening | [Screening ledger](data/screening.json) · [Pending](docs/PENDING.md) |",
                  "| Contribute | [Contributing](CONTRIBUTING.md) · [Changelog](CHANGELOG.md) |", "",
                  "Edit the data, then run the commands below. GitHub Actions checks catalogue consistency; it does not automatically add papers.", ""]
    lines += ["```sh", "python scripts/render.py", "python scripts/validate.py", "```", "",
              "[Changelog](CHANGELOG.md) · [Contributing](CONTRIBUTING.md) · [CC BY 4.0](LICENSE)", "",
              ("原创整理内容使用 CC BY 4.0；脚本使用 MIT。论文、数据集和第三方代码保留其各自许可。本仓库不托管论文全文，也不代表 TypeSafe 或任何模型作者。" if zh else
               "Original curation is CC BY 4.0; scripts are MIT. Papers, datasets, and third-party code retain their own licenses. This repository does not host paper full texts and is not affiliated with TypeSafe or the model authors."), "",
              ("[回到顶部](#top)" if zh else "[Back to top](#top)"), ""]
    return "\n".join(lines)


def evidence(data):
    lines = ["<!-- Generated by scripts/render.py. -->", "# Evidence ledger / 收录证据", "",
             "Short excerpts support relevance decisions, not paper quality or reproducibility. Scores measure topic fit and substantive contribution only. Abstract-level review is the default; targeted full-text checks are marked. 引文用于核实相关性，不是论文质量或模型性能评分。", ""]
    for p in ordered(data["papers"]):
        pid = p["arxiv_id"]
        lines += [f'<a id="evidence-{pid.replace(".", "-")}"></a>',
                  f"## {pid} — {p['title']}", "",
                  f"**{p['relation_level']}** · Relevance {p['relevance']['weighted_total']:.2f} · {p['review_level']} · Verified {p['verified_on']}", "",
                  p["relation"]["en"], "", p["relation"]["zh"], ""]
        for e in p["evidence"]:
            lines.append(f"- **{e['criterion']}**: “{e['quote']}” — [{e['location']}]({e['source_url']})")
        lines += ["", f"Metadata: [reviewed v{p['version']}]({p['reviewed_url']}); first submitted {p['first_submitted']}; updated {p['updated']}. Full authors: " + "; ".join(p["authors"]) + ".", ""]
    return "\n".join(lines)


def bib_escape(s):
    return s.replace("\\", r"\textbackslash{}").replace("{", r"\{").replace("}", r"\}").replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#").replace("$", r"\$")


def bibtex(data):
    lines = ["% Generated from data/papers.json. Versions pin the reviewed snapshot.", ""]
    for p in ordered(data["papers"]):
        lines += ["@misc{arxiv" + p["arxiv_id"].replace(".", "") + ",",
                  "  title = {{" + bib_escape(p["title"]) + "}},",
                  "  author = {" + " and ".join(bib_escape(n) for n in p["authors"]) + "},",
                  "  year = {" + p["first_submitted"][:4] + "},",
                  "  eprint = {" + p["arxiv_id"] + "},",
                  "  archivePrefix = {arXiv},",
                  "  primaryClass = {" + p["arxiv_categories"][0] + "},",
                  "  url = {" + p["reviewed_url"] + "},",
                  "  note = {Version " + str(p["version"]) + "; reviewed " + p["verified_on"] + "}", "}", ""]
    return "\n".join(lines)


def outputs(data):
    return {"README.md": readme(data, "en"), "README.zh-CN.md": readme(data, "zh"),
            "docs/EVIDENCE.md": evidence(data), "references.bib": bibtex(data)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed generated files are stale")
    args = parser.parse_args()
    stale = []
    for name, content in outputs(load()).items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("Stale generated files: " + ", ".join(stale))
    print("Generated files are current." if args.check else "Rendered bilingual catalogue, evidence and BibTeX.")


if __name__ == "__main__":
    main()
